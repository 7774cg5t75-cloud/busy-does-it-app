import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {makeWebsiteRecoveryPoint,restoreWebsiteRecoveryPoint} from "../src/core/websiteRecoveryPoint.mjs";
const read=p=>readFileSync(new URL("../"+p,import.meta.url),"utf8");
const draft={id:"owner-1",generation:4,publicStatus:"Published",sections:[{id:"hero",title:"Before"}]};
const point=makeWebsiteRecoveryPoint(draft,"2026-10-11T16:00:00Z");
assert.equal(point.ok,true);
assert.equal(point.privateOnly,true);
const current={...draft,generation:8,sections:[{id:"hero",title:"After"}],publicStatus:"Published now"};
const restored=restoreWebsiteRecoveryPoint(current,point,s=>({...s,generation:s.generation+1}));
assert.equal(restored.applied,true);
assert.equal(restored.draft.generation,9);
assert.equal(restored.draft.sections[0].title,"Before");
assert.equal(restored.draft.publicStatus,"Published now");
assert.equal(current.sections[0].title,"After");
assert.equal(restoreWebsiteRecoveryPoint({...current,id:"another-owner"},point,s=>s).applied,false);
assert.equal(restoreWebsiteRecoveryPoint(current,{...point,draftId:"another-owner"},s=>s).applied,false);
assert.equal(restoreWebsiteRecoveryPoint(current,point,()=>{throw Error("offline");}).applied,false);
const c=read("src/app/AppController.js");
assert.ok(c.includes("setWebsiteRecoveryPoint(null)"),"Logout clears session recovery");
assert.ok(c.includes("restoreWebsiteRecoverySnapshot(current,websiteRecoveryPoint,rebuildPrivateWebsiteDraft,websiteHistoryScope)"));
assert.ok(c.includes("setWebsiteUndo(items=>[...items,current].slice(-8))"));
assert.ok(!read("src/core/websiteRecoveryPoint.mjs").includes("fetch("));
const ui=read("src/screens/websiteBuilder.js");
assert.ok(ui.includes("Yes, restore my saved design"));
assert.ok(ui.includes("Cancel restoration"));
console.log("V3.149 RECOVERY PASS: single private session checkpoint, tenant-bound restoration, fresh revision, unchanged public status, one Undo and explicit confirmation.");
