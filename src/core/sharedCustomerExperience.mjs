/**
 * V3.172 — shared customer-journey review for website and Business App.
 *
 * Two existing builders, one bounded set of customer goals. This adapter
 * deliberately does not copy customer information, privately saved website
 * content, media, public URLs or raw service descriptions into its findings.
 * It NEVER asserts that a form or booking path actually works from config.
 */
import {websiteQualityGuidance} from "./websiteQualityGuidance.mjs";
import {reviewCustomerExperience} from "./appCustomerExperienceReview.mjs";
import {websiteJourneyAssurance} from "./websiteJourneyAssurance.mjs";
const GOALS=Object.freeze(["book","enquire","services","photos","offers","rewards"]);
const knownWebsiteQuality=Object.freeze({
 facts:["Check your approved business details","Review the business name, service area and contact details in your website settings."],
 description:["Clarify what the business offers","Add an accurate description in your website content editor."],
 personality:["Explain why someone should choose you","Use a truthful owner-approved differentiator, not an invented testimonial."],
 photos:["Review website photographs","Add your own licensed and approved photos."],
 services:["Explain your main services clearly","Write accurate service descriptions in the website content editor."],
 style:["Review the website visual direction","Choose a style and compare it with your existing private design."]
});
const webAction={
 book:["Check how someone requests a booking","A website section or contact link is not proof of a working booking request. Verify the exact customer form and diary confirmation in staging."],
 enquire:["Check how visitors make an enquiry","A visible Contact section is not proof of submission, business notification or customer reply. Verify those separately."],
 services:["Make services understandable","Check names and explanations against approved business information, across the website and app."],
 photos:["Check real images and descriptions","Use approved images and useful alternative text; compare phone and wide layouts."],
 offers:["Check offers and terms","Only present genuinely approved offers, validity dates and eligibility."],
 rewards:["Verify loyalty promises","Do not imply customers can earn or redeem rewards on the website until that supported flow is tested."]
};
function reviewSharedCustomerGoal({
 goal="enquire",websiteDraft=null,brandBrain={},appConfig=null,
 websiteJourney=null,websitePublishing=null,websiteProof=null
}={}){
 if(!GOALS.includes(goal))return {ok:false,reason:"Choose a supported customer goal."};
 const availableWebsite=websiteDraft&&typeof websiteDraft==="object"&&
  Array.isArray(websiteDraft.sections)&&typeof websiteDraft.id==="string"&&
  websiteDraft.id.length>0;
 const availableApp=appConfig&&typeof appConfig==="object"&&
  Array.isArray(appConfig.modules);
 if(!availableWebsite&&!availableApp)return {
  ok:false,reason:"A current private website or Business App draft is required."};
 const findings=[];
 if(availableWebsite){
  const guidance=websiteQualityGuidance({brandBrain,draft:websiteDraft});
  for(const entry of guidance.suggestions.slice(0,12)){
   const script=knownWebsiteQuality[entry.id];
   if(script)findings.push({id:"website_"+entry.id,
    surface:"website",priority:entry.id==="facts"?"important":"review",
    title:script[0],ownerAction:script[1],
    kind:"owner_content_or_design_review",automaticChange:false});
  }
  if(["book","enquire","offers","rewards"].includes(goal))
   findings.push({id:"website_"+goal+"_delivery",surface:"website",
    priority:"important",title:webAction[goal][0],
    ownerAction:webAction[goal][1],
    kind:"unverified_customer_action",automaticChange:false});
 }
 let app=null;
 if(availableApp){
  const result=reviewCustomerExperience(appConfig,{goal});
  if(!result.ok)return {ok:false,reason:result.reason};
  app=result;
  for(const item of result.improvements.slice(0,6)){
   // Only finite labels and explanations generated by our own app review
   // engine are carried forward. Never export the preview's nextConfig.
   findings.push({id:"app_"+item.id,surface:"app",
    priority:item.priority==="important"?"important":"review",
    title:item.title,ownerAction:item.ownerAction,
    kind:"existing_app_editor_or_staging_check",automaticChange:false});
  }
 }
 const websiteAssurance=availableWebsite?websiteJourneyAssurance({
  journey:websiteJourney,publishing:websitePublishing,proof:websiteProof,
  hasDraft:true}):null;
 const appStatus=app?app.taskStatus:null;
 const requiresTesting=["book","enquire","offers","rewards"].includes(goal);
 const priorityOrder={important:0,review:1};
 findings.sort((a,b)=>priorityOrder[a.priority]-priorityOrder[b.priority]);
 return {ok:true,kind:"shared_customer_experience_review_v3172",
  goal,websitePresent:!!availableWebsite,appPresent:!!availableApp,
  websitePublicationState:websiteAssurance?.action||"not_assessed",
  websiteDeliveryVerified:websiteAssurance?.publicWebsiteVerified===true,
  appTaskStatus:appStatus||"not_assessed",
  findings:findings.slice(0,12),
  totalFindings:findings.length,
  websiteAction:{
   id:goal,title:webAction[goal][0],instruction:webAction[goal][1],
   verified:false
  },
  appHasReversibleLayoutIdea:app?.hasReversibleNavigationSuggestion===true,
  unverifiedOperationalJourney:requiresTesting,
  noClaimsOfRealSubmission:true,
  noCopyOrPhotoRewritten:true,neverTurnsOnFeatures:true,
  noCrossBusinessJoin:true,oneCurrentDraftPerSurface:true,
  ownerApprovalRequired:true,notConversionEvidence:true,
  noCustomerDataIncluded:true,noPublishing:true,noCharges:true};
}
export {GOALS,reviewSharedCustomerGoal};
